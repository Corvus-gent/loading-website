import { readFile, mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { chromium, webkit } from '@playwright/test';

const origin = process.env.OPENRISK_TEST_ORIGIN || 'https://corvus.gent';
const password = process.env.OPENRISK_TEST_PASSWORD || (process.env.OPENRISK_TEST_BRIEF
  ? (await readFile(process.env.OPENRISK_TEST_BRIEF,'utf8')).match(/password `([^`]+)`/)[1] : '');
const engine = process.env.OPENRISK_TEST_WEBKIT ? webkit : chromium;
const size = process.env.OPENRISK_TEST_MOBILE ? {width:390,height:844} : {width:1440,height:900};
const screens = process.env.OPENRISK_TEST_SCREENS;
const root = origin + '/project-cto';
const browser = await engine.launch({ headless:true });
const measurements = {};
const errors = [];
try {
  if (screens) await mkdir(screens,{recursive:true});
  const page = await browser.newPage({ viewport:size, reducedMotion:'reduce' });
  page.setDefaultTimeout(12000);
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',response=>{
    if (response.status()>=500 && response.url().startsWith(origin)) console.log('Service status',response.status(),new URL(response.url()).pathname);
  });
  const shot = async name => { if(screens) await page.screenshot({path:screens+'/'+name+'.png',animations:'disabled',fullPage:true}); };
  const gate = await page.goto(root);
  assert.equal(gate.status(),401);
  assert.equal(gate.headers()['x-robots-tag'],'noindex, nofollow');
  for (const path of ['/api/bootstrap','/api/state','/workspace.js','/document/pdf.mjs','/startup/aikido-security','/unknown']) assert.equal((await page.request.get(root+path)).status(),401);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button',{name:'Open workspace'}).click();
  await page.getByRole('heading',{name:'Ecosystem map'}).waitFor();
  await shot('01-ecosystem-map');
  async function search(name) {
    const started = Date.now();
    await page.locator('#company-search').fill(name);
    const dropdown = page.locator('#search-results');
    const profile = dropdown.getByRole('button',{name:new RegExp('^'+name)}).first();
    await profile.waitFor();
    const ready = Date.now();
    await profile.click();
    await page.getByRole('heading',{name,exact:true}).waitFor();
    measurements[name]={typeaheadMs:ready-started,profileMs:Date.now()-ready};
  }
  const explore=()=>page.locator('#top-nav').getByRole('button',{name:'Explore'}).click();
  for (const name of ['Aikido Security','Deliverect','Stripe']) {
    await search(name);
    await page.getByRole('heading',{name:'OpenRisk score'}).waitFor();
    if(name==='Aikido Security') await shot('02-aikido-dossier');
    await explore();
  }
  await page.getByRole('group',{name:'Map region'}).getByRole('button',{name:'Bay Area',exact:true}).click();
  await page.getByRole('button',{name:'Palo Alto',exact:true}).click();
  await page.getByRole('heading',{name:/Palo Alto ·/}).waitFor();
  const started = Date.now();
  await page.locator('#company-search').fill('Hugging Face');
  await page.getByRole('button',{name:/Research Hugging Face/}).click();
  await page.getByRole('heading',{name:'Hugging Face',exact:true}).waitFor();
  measurements.coldFirstPaintMs=Date.now()-started;
  await page.waitForFunction(()=>!document.querySelector('.shimmer'));
  measurements.coldSettledMs=Date.now()-started;
  await shot('03-cold-research');
  await explore();
  await search('Aikido Security');
  await page.getByRole('button',{name:'Follow',exact:true}).click();
  await page.getByRole('button',{name:'Following',exact:true}).waitFor();
  const investorWrite = await page.request.post(root+'/api/state',{headers:{Origin:origin},data:{action:'save',company:'aikido-security',period:'2026-10',values:{cash:10},currency:'EUR'}});
  assert.equal(investorWrite.status(),403);
  await page.getByRole('button',{name:'Claim this profile'}).click();
  await page.getByRole('heading',{name:'My startup'}).waitFor();
  await page.getByRole('button',{name:'September investor update'}).click();
  await page.getByRole('button',{name:'Extract KPI proposals'}).click();
  await page.getByRole('heading',{name:'Review proposals'}).waitFor();
  assert.equal(await page.locator('[data-proposal]').count(),7);
  await page.getByRole('button',{name:'Confirm all'}).click();
  await page.getByText('7 KPI proposals confirmed.').waitFor();
  await page.getByRole('button',{name:'October investor update'}).click();
  await page.getByRole('button',{name:'Extract KPI proposals'}).click();
  await page.getByRole('heading',{name:'Review proposals'}).waitFor();
  await shot('04-email-proposals');
  await page.getByRole('button',{name:'Confirm all'}).click();
  await page.getByText('7 KPI proposals confirmed.').waitFor();
  await page.getByRole('button',{name:'Find investors',exact:true}).click();
  await page.getByRole('heading',{name:'Notion Capital'}).waitFor();
  await shot('05-investor-fit');
  await page.getByRole('button',{name:'My startup',exact:true}).click();
  await page.getByLabel('Email',{exact:true}).fill('sam@example.com');
  await page.getByRole('button',{name:'Create 7-day link'}).click();
  const guestLink = page.getByLabel('Private demo link');
  await guestLink.waitFor();
  const invited = await browser.newPage({viewport:size});
  invited.setDefaultTimeout(12000);
  try {
    const inviteUrl=await guestLink.inputValue();
    const invitePath=new URL(inviteUrl).pathname;
    assert.equal((await invited.goto(inviteUrl)).status(),401);
    await invited.getByLabel('Password').fill(password);
    await invited.getByRole('button',{name:'Open workspace'}).click();
    await invited.getByRole('heading',{name:'Confirmed KPIs'}).waitFor();
    assert.equal(new URL(invited.url()).pathname,invitePath);
    await page.getByRole('button',{name:'Revoke'}).click();
    await page.getByText('Invitation revoked.').waitFor();
    await invited.reload();
    await invited.getByText('This invitation has expired or been revoked.').waitFor();
  } finally { await invited.close(); }
  await page.locator('#top-nav').getByRole('button',{name:'Watchlist',exact:true}).click();
  await page.getByRole('heading',{name:'Watchlist'}).waitFor();
  await page.getByText('4.6 mo').waitFor();
  await page.getByText('11%',{exact:true}).waitFor();
  await shot('06-portfolio-cockpit');
  await explore();
  await page.getByRole('button',{name:'Suggest startup'}).click();
  await page.getByRole('button',{name:'Submit for approval'}).click();
  await page.getByRole('alert').getByText('Enter a startup name or website.').waitFor();
  await page.getByLabel('Startup name').fill('Northstar Demo');
  await page.getByRole('button',{name:'Submit for approval'}).click();
  await page.getByText('Submitted to the admin queue.').waitFor();
  await page.getByRole('button',{name:'Suggest startup'}).click();
  await page.getByLabel('Website').fill('example.com');
  await page.getByLabel('City (optional)').fill('Gent');
  await page.getByRole('button',{name:'Submit for approval'}).click();
  await page.getByText('Submitted to the admin queue.').waitFor();
  await page.locator('#top-nav').getByRole('button',{name:'Manage map',exact:true}).click();
  await page.getByRole('heading',{name:'Manage map'}).waitFor();
  const proposed = label => page.getByRole('row').filter({hasText:label});
  await proposed('Northstar Demo').getByLabel('Map city').fill('Gent');
  await proposed('Northstar Demo').getByRole('button',{name:'Approve & preload'}).click();
  await proposed('Northstar Demo').getByText('approved',{exact:true}).waitFor();
  await proposed('example.com').getByRole('button',{name:'Approve & preload'}).click();
  await proposed('example.com').getByText('approved',{exact:true}).waitFor();
  await shot('07-admin-queue');
  const {state:{approved}} = await (await page.request.get(root+'/api/state')).json();
  const fromWebsite=approved.find(company=>company.domain==='example.com');
  assert.equal(fromWebsite.city,'Gent');
  await page.goto(root+'/city/gent');
  await page.locator('#city-rows [data-company="'+fromWebsite.id+'"]').waitFor();
  await search('Northstar Demo');
  await page.reload();
  await page.getByRole('heading',{name:'Northstar Demo',exact:true}).waitFor();
  await explore();
  await page.getByRole('button',{name:'+ Add city',exact:true}).click();
  await page.getByLabel('City name').fill('Paris');
  await page.getByRole('button',{name:'Start preload'}).click();
  await page.getByRole('heading',{name:/Paris ·/}).waitFor();
  assert.equal(await page.locator('#city-rows').getByRole('button').count()>0,true);
  if (process.env.OPENRISK_TEST_PDF && process.env.OPENRISK_TEST_XLSX) {
    await page.locator('#top-nav').getByRole('button',{name:'My startup',exact:true}).click();
    await page.getByRole('heading',{name:'My startup'}).waitFor();
    await page.locator('input[type=file]').setInputFiles([process.env.OPENRISK_TEST_PDF,process.env.OPENRISK_TEST_XLSX]);
    await page.getByRole('button',{name:'Extract KPI proposals'}).click();
    await page.getByRole('heading',{name:'Review proposals'}).waitFor();
    assert.equal(await page.locator('[data-proposal]').count(),4);
    await page.getByText('September update.pdf',{exact:true}).first().waitFor();
    await page.getByText('October update.xlsx',{exact:true}).first().waitFor();
  }
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true,'No page overflow');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify(measurements,null,2));
} finally {
  if (errors.length) console.error(errors);
  await browser.close();
}
