// Keep the authoring bank in games/data; ship it only inside the server bundle.
import fs from 'node:fs';
const bank=Object.fromEntries(['countries','languages','words','artists'].map(name=>[name,JSON.parse(fs.readFileSync(`games/data/${name}.json`))]));
fs.writeFileSync('api/_game-data.js','// Generated by tools/build-game-data.mjs. Server-only; never import from browser code.\nexport default '+JSON.stringify(bank)+';\n');
