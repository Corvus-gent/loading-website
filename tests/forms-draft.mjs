import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { createFormDraft } from '../js/forms-draft.js';
globalThis.crypto ||= webcrypto;
globalThis.window = new EventTarget();
globalThis.document = new EventTarget();
document.visibilityState = 'visible';
Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { sendBeacon: () => false } });
const storage = () => { const rows = new Map(); return { getItem: key => rows.get(key) || null, setItem: (key, value) => rows.set(key, value) }; };
const ok = result => ({ ok: true, status: 200, json: async () => result });
let status = [], sent = [];
const blocked = () => { throw new Error('SecurityError: storage blocked'); };
Object.defineProperty(window, 'localStorage', { configurable: true, get: blocked });
const privateDraft = createFormDraft({ slug: 'fixture', onStatus: m => status.push(m), request: async (_url, options) => { sent.push(JSON.parse(options.body)); return ok({ sent: true }); } });
privateDraft.change({ idea: { text: 'private mode answer' } });
await privateDraft.done(); privateDraft.destroy();
assert.equal(sent[0].answers.idea.text, 'private mode answer');
assert(status.some(s => s.includes('cannot keep a draft')), 'blocked localStorage must not prevent rendering/submission');
const memory = storage();
memory.setItem('corvus.forms.draft:fixture', JSON.stringify({ updatedAt: '2099-01-01T00:00:00Z', answers: { obsolete: { text: 'removed question' }, idea: { text: 'kept answer' } } }));
let restored;
const repaired = createFormDraft({ slug: 'fixture', allowedIds: ['idea'], storage: memory, onRestore: a => restored = a, request: async (_url, options) => { sent.push(JSON.parse(options.body)); return ok({ sent: true }); } });
assert.deepEqual(restored, { idea: { text: 'kept answer' } });
await repaired.done(); repaired.destroy();
assert(Date.parse(sent.at(-1).updatedAt) <= Date.now(), 'a restored future clock must not permanently poison saves');
// A missing/throwing beacon must use fetch keepalive with the newest draft.
navigator.sendBeacon = () => { throw Error('beacon unavailable'); };
let fallback;
const exiting = createFormDraft({ slug: 'fixture', storage: storage(), request: async (url, options) => { fallback = { url, options }; return ok({ sent: true }); } });
exiting.change({ idea: { text: 'final keystroke' } });
window.dispatchEvent(new Event('pagehide'));
assert.equal(fallback.url, '/api/forms/flush');
assert.equal(fallback.options.keepalive, true);
assert.equal(JSON.parse(fallback.options.body).answers.idea.text, 'final keystroke');
exiting.destroy(); await new Promise(r => setTimeout(r, 0));
// Stalled requests must release Done instead of disabling the whole form forever.
const stalled = createFormDraft({ slug: 'fixture', storage: storage(), requestTimeouts: { save: 15, flush: 15 }, request: (_url, { signal }) => new Promise((_, reject) => signal.addEventListener('abort', () => reject(new Error('aborted')), { once: true })) });
stalled.change({ idea: { text: 'retained offline' } });
await assert.rejects(stalled.done(), /aborted/); stalled.destroy();
console.log('PASS: blocked storage, stale config/future clock recovery, beacon fallback and request deadlines.');
let networkOnline = false, attempts = 0;
const reconnecting = createFormDraft({ slug: 'fixture', storage: storage(), request: async () => { attempts++; if (!networkOnline) throw Error('offline'); return ok({ sent: true }); } });
reconnecting.change({ idea: { text: 'answer written offline' } });
await assert.rejects(reconnecting.done(), /offline/);
networkOnline = true; window.dispatchEvent(new Event('online'));
await new Promise(resolve => setTimeout(resolve, 5));
assert.equal(attempts, 2, 'reconnection immediately saves the draft instead of waiting for a retry timer');
reconnecting.destroy();
console.log('PASS: drafts recover immediately when the browser comes back online.');
